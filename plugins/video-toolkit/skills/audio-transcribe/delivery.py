"""Validated document rendering and collision-safe publication, no model calls."""
import os
import re
import tempfile
from pathlib import Path

from subtitles import format_timestamp, join_word_texts

SUFFIXES = {"srt": ".srt", "md-timed": ".timed.md", "md": ".md", "txt": ".txt", "json": ".json"}


def content_key(text):
    """Compare lexical content across whitespace/punctuation layout changes."""
    return "".join(ch.casefold() for ch in text if ch.isalnum())


def paragraphs(result, gap=2.0, max_chars=450):
    segments = result.get("segments") or []
    if not segments:
        raw = (result.get("text") or "").strip()
        groups = []
        for block in re.split(r"\n\s*\n", raw):
            current = ""
            for sentence in re.findall(r".+?(?:[。！？!?]|\.(?=\s|$)|$)", block, flags=re.S):
                current += sentence
                if len(current) >= max_chars:
                    groups.append(current.strip())
                    current = ""
            if current.strip():
                groups.append(current.strip())
        return [{"text": p, "start": None, "end": None} for p in groups if p]
    groups, current = [], None
    for seg in segments:
        if current and (seg["start"] - current["end"] >= gap
                        or seg.get("speaker_id") != current.get("speaker_id")
                        or (len(current["text"]) >= max_chars and re.search(r"[.!?。！？][\"”’']?$", current["text"]))):
            groups.append(current)
            current = None
        if current is None:
            current = dict(seg)
        else:
            current["text"] = join_word_texts([current["text"], seg["text"]])
            current["end"] = seg["end"]
    if current:
        groups.append(current)
    return groups


def markdown(result, timed=False):
    groups = paragraphs(result)
    if timed and any(p["start"] is None for p in groups):
        raise ValueError("Timed Markdown requires actual aligned timestamps")
    rendered = []
    for p in groups:
        # Escape Markdown controls; do not invent headings, summaries or prose.
        text = re.sub(r"([\\`*_{}\[\]<>#])", r"\\\1", p["text"])
        if timed:
            text = f"[{format_timestamp(p['start'])} --> {format_timestamp(p['end'])}]\n\n{text}"
        rendered.append(text)
    return "\n\n".join(rendered) + ("\n" if rendered else "")


def publish(output_dir, stem, contents):
    from job_cache import cache_root, JobLock
    import hashlib
    identity = (str(Path(output_dir).resolve()) + "/" + stem).casefold()
    directory = cache_root() / "publication-locks" / hashlib.sha256(identity.encode()).hexdigest()
    directory.mkdir(parents=True, exist_ok=True)
    with JobLock(directory, blocking=True):
        return _publish(output_dir, stem, contents)


def _publish(output_dir, stem, contents):
    """Stage all files, then link without replace; roll back only our own links.

    Hard links provide atomic no-clobber publication on local Mac/Windows
    filesystems. An unsupported filesystem fails with no completed products.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    staged = {}
    try:
        for kind, content in contents.items():
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                             dir=output_dir, prefix=".transcribe-", delete=False) as f:
                f.write(content)
                f.flush()
                os.fsync(f.fileno())
                staged[kind] = Path(f.name)
        number = 1
        while True:
            base = stem if number == 1 else f"{stem}_{number}"
            targets = {kind: output_dir / (base + SUFFIXES[kind]) for kind in contents}
            # Include every supported suffix to avoid mismatching an existing
            # SRT with an unrelated MD generated by a later invocation.
            if any((output_dir / (base + suffix)).exists() for suffix in SUFFIXES.values()):
                number += 1
                continue
            created = []
            try:
                for kind, path in targets.items():
                    os.link(staged[kind], path)
                    created.append(path)
                return targets
            except FileExistsError:
                for path in created:
                    path.unlink()
                number += 1
            except BaseException:
                for path in created:
                    path.unlink()
                raise
    finally:
        for path in staged.values():
            path.unlink(missing_ok=True)
